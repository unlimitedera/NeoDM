using System.Diagnostics;
using NDM.Core;
using static NDM.Tests.StreamKit;

namespace NDM.Tests;

/// <summary>Opt-in test with the real pinned ffmpeg (about 115 MB download). Not part of build.ps1.
/// Run: dotnet run --project tests/NDM.Tests -c Release -- --real-ffmpeg
/// It installs the pinned build into a scratch folder through ToolManager (https, pinned host, SHA-256), generates HLS and DASH fixtures with it,
/// serves them from a local server, downloads them with the engine and checks the results with ffmpeg again.</summary>
internal static class StreamRealTests
{
    private static int failures;

    private static void Report(string name, bool ok, string detail) { if (!ok) failures++; Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {name}: {detail}"); }

    public static async Task<int> Run(string root)
    {
        var state = Path.Combine(root, "real-state"); var downloads = Path.Combine(root, "real-downloads"); var fixtures = Path.Combine(root, "real-fixtures");
        Directory.CreateDirectory(fixtures);
        var tools = new ToolManager(state);
        Console.WriteLine($"Pinned build: {ToolManager.FfmpegPin.Version}\n  {ToolManager.FfmpegPin.Url}\n  archive SHA-256 {ToolManager.FfmpegPin.ArchiveSha256}\n  ffmpeg.exe SHA-256 {ToolManager.FfmpegPin.ExeSha256}");
        var clock = Stopwatch.StartNew(); long lastReport = 0;
        try
        {
            await tools.InstallAsync(new Progress<(long Done, long Total)>(p => { if (p.Done - lastReport > 20_000_000 || p.Done == p.Total) { lastReport = p.Done; Console.WriteLine($"  downloaded {p.Done / 1_000_000} of {p.Total / 1_000_000} MB"); } }));
        }
        catch (ToolException ex) { Console.WriteLine($"BLOCKED: the tool could not be installed ({ex.Code}): {ex.Message}"); return 2; }
        Report("install", tools.IsInstalled, $"installed {tools.GetVersion()} in {clock.Elapsed.TotalSeconds:0} s, hash verified twice");
        var version = await tools.RunAsync(new[] { "-version" }, TimeSpan.FromSeconds(60));
        Report("launch", version.ExitCode == 0, version.Output.Split('\n')[0].Trim());

        async Task<bool> Gen(params string[] args)
        {
            var r = await tools.RunAsync(new[] { "-hide_banner", "-loglevel", "error", "-y" }.Concat(args).ToArray(), TimeSpan.FromMinutes(3), default, fixtures);
            if (r.ExitCode != 0) Console.WriteLine("  generator error: " + r.Error);
            return r.ExitCode == 0;
        }
        string[] Src = { "-f", "lavfi", "-i", "testsrc=duration=6:size=320x180:rate=25", "-f", "lavfi", "-i", "sine=frequency=440:duration=6" };
        foreach (var d in new[] { "ts", "fv", "fa", "dash" }) Directory.CreateDirectory(Path.Combine(fixtures, d));
        bool ok = await Gen(Src.Concat(new[] { "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-f", "hls", "-hls_time", "2", "-hls_playlist_type", "vod", "-hls_segment_filename", "ts/seg%d.ts", "ts/index.m3u8" }).ToArray())
            && await Gen(Src.Concat(new[] { "-map", "0:v", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-f", "hls", "-hls_time", "2", "-hls_playlist_type", "vod", "-hls_segment_type", "fmp4", "-hls_fmp4_init_filename", "init.mp4", "-hls_segment_filename", "fv/seg%d.m4s", "fv/index.m3u8" }).ToArray())
            && await Gen(Src.Concat(new[] { "-map", "1:a", "-c:a", "aac", "-f", "hls", "-hls_time", "2", "-hls_playlist_type", "vod", "-hls_segment_type", "fmp4", "-hls_fmp4_init_filename", "init.mp4", "-hls_segment_filename", "fa/seg%d.m4s", "fa/index.m3u8" }).ToArray())
            && await Gen(Src.Concat(new[] { "-map", "0:v", "-map", "1:a", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-f", "dash", "-seg_duration", "2", "-use_template", "1", "-use_timeline", "1", "-adaptation_sets", "id=0,streams=v id=1,streams=a", "dash/manifest.mpd" }).ToArray());
        Report("fixtures", ok, "HLS (ts), HLS (fMP4 video and audio), DASH generated by the pinned build");
        if (!ok) return 1;

        using var server = new StreamServer();
        foreach (var file in Directory.GetFiles(fixtures, "*", SearchOption.AllDirectories))
            server.Add("/" + Path.GetRelativePath(fixtures, file).Replace('\\', '/'), File.ReadAllBytes(file));
        server.Add("/fm/master.m3u8", "#EXTM3U\n#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"aud\",NAME=\"Sound\",DEFAULT=YES,AUTOSELECT=YES,URI=\"../fa/index.m3u8\"\n#EXT-X-STREAM-INF:BANDWIDTH=400000,RESOLUTION=320x180,CODECS=\"avc1.640015,mp4a.40.2\",AUDIO=\"aud\"\n../fv/index.m3u8\n");

        var options = new DownloadOptions { MaxConcurrentDownloads = 2, StreamConnections = 8, Tools = tools };
        using var manager = new DownloadManager(downloads, state, options);

        async Task<DownloadJob> Download(string url, StreamKind kind, bool mp4, string name)
        {
            var job = await manager.AddStreamAsync(url, kind, preferMp4: mp4, fileName: name);
            await WaitUntil(() => JobOf(manager, job.Id).Status is "Completed" or "Failed", "stream job did not finish", 120);
            return JobOf(manager, job.Id);
        }
        async Task Verify(string name, DownloadJob job, string extension, double seconds)
        {
            if (job.Status != "Completed") { Report(name, false, "job failed: " + Describe(job)); return; }
            var decode = await tools.RunAsync(new[] { "-hide_banner", "-v", "error", "-i", job.FilePath, "-f", "null", "-" }, TimeSpan.FromMinutes(2));
            var info = await tools.RunAsync(new[] { "-hide_banner", "-i", job.FilePath }, TimeSpan.FromMinutes(1));
            var duration = FfmpegCommands.ParseDuration(info.Error + info.Output);
            bool good = decode.ExitCode == 0 && decode.Error.Trim().Length == 0 && Path.GetExtension(job.FilePath) == extension && duration is { } d && Math.Abs(d - seconds) <= seconds * 0.1 && job.StreamNote is null;
            Report(name, good, $"{Path.GetFileName(job.FilePath)} {new FileInfo(job.FilePath).Length} bytes, duration {duration:0.00} s, decode exit {decode.ExitCode} {decode.Error.Trim()}, note {job.StreamNote ?? "none"}");
        }

        await Verify("hls ts -> ts (no tool needed)", await Download(server.Url("/ts/index.m3u8"), StreamKind.Hls, false, "real-ts"), ".ts", 6);
        await Verify("hls ts -> mp4 (rewrap, copy)", await Download(server.Url("/ts/index.m3u8"), StreamKind.Hls, true, "real-ts-mp4"), ".mp4", 6);
        await Verify("hls fmp4 video + audio -> mp4 (mux, copy)", await Download(server.Url("/fm/master.m3u8"), StreamKind.Hls, false, "real-fmp4"), ".mp4", 6);
        await Verify("dash video + audio -> mp4 (mux, copy)", await Download(server.Url("/dash/manifest.mpd"), StreamKind.Dash, false, "real-dash"), ".mp4", 6);
        Console.WriteLine(failures == 0 ? "REAL RESULT: all passed" : $"REAL RESULT: {failures} failed");
        return failures == 0 ? 0 : 1;
    }

    private static async Task WaitUntil(Func<bool> condition, string message, int seconds) => await StreamKit.WaitUntil(condition, message, seconds);
}
